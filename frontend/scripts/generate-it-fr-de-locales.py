def load_overrides(lang: str) -> dict[str, dict[str, str]]:
    merged: dict[str, dict[str, str]] = {}
    for source in (LOCALES.get(lang, {}),):
        for ns, strings in source.items():
            merged.setdefault(ns, {}).update(strings)
    extra = OVERRIDES_DIR / f"{lang}.json"
    if extra.is_file():
        file_data = json.loads(extra.read_text(encoding="utf-8"))
        for ns, strings in file_data.items():
            merged.setdefault(ns, {}).update(strings)
    return merged


def main() -> None:
    en_files = sorted(EN.glob("*.json"))
    namespaces = [p.stem for p in en_files]

    for lang in LOCALES:
        overrides = load_overrides(lang)
        out_dir = ROOT / lang
        out_dir.mkdir(parents=True, exist_ok=True)
        for ns in namespaces:
            en_data = json.loads((EN / f"{ns}.json").read_text(encoding="utf-8"))
            data = dict(en_data)
            if ns in overrides:
                for key, value in overrides[ns].items():
                    if key not in en_data:
                        raise KeyError(f"{lang}/{ns}: unknown key {key!r}")
                    data[key] = value
            untranslated = [k for k, v in data.items() if v == en_data[k]]
            path = out_dir / f"{ns}.json"
            path.write_text(
                json.dumps(data, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            if untranslated and lang in overrides and ns in overrides:
                still_en = [k for k in untranslated if k not in overrides[ns]]
                if still_en:
                    raise KeyError(f"{lang}/{ns}: untranslated keys {still_en!r}")
        print(f"wrote {lang}: {len(namespaces)} namespaces")


if __name__ == "__main__":
    main()
